import AppKit

/// Whether a copy off the line carries the formatting it was copied with.
///
/// Off by default, because the words are what most pastes want: a terminal
/// or an editor has no use for a dressed-up document, and the user who
/// copies into one never asked for one. The switch is read when a card goes
/// out — copied, pasted — never when it arrives, so turning it on covers the
/// cards already hanging. The drag is left out on purpose: `GrabArea`
/// carries plain text alone, where the wider set was tried and made Chromium
/// refuse the drop.
///
/// Top level and unisolated, because it is read from `PasteInto` and the
/// menu as well as here, and a preference is not a piece of actor state.
enum FormatCopy {
    private static let key = "copyWithFormatting"
    /// Absent means off, which `bool(forKey:)` already answers.
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: key) }
        set { UserDefaults.standard.set(newValue, forKey: key) }
    }
}

/// How a copied picture file hangs: as the picture it is, or as the file
/// reference any file would be.
///
/// A picture card keeps its own copy in the app's folder, so its card
/// outlives the original — delete the file on the Desktop and the picture
/// stays hanging, which is the promise a picture on this line makes. A copy
/// is also a duplicate, so the copying is bounded: files over the limit hang
/// as references, exactly like any other file. With the switch off, the
/// promise is the file card's instead: the original is the thing the card
/// points at, and its deletion is the card's to wear.
enum ImageFileHanging {
    private static let enabledKey = "imageFilesHangAsPictures"
    private static let limitKey = "imageFileCopyLimitMB"
    /// On unless written off, the way the clipboard watch is.
    static var isEnabled: Bool {
        get {
            guard UserDefaults.standard.object(forKey: enabledKey) != nil else { return true }
            return UserDefaults.standard.bool(forKey: enabledKey)
        }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }
    static let defaultLimitMB = 16
    static var limitMB: Int {
        get {
            guard let stored = UserDefaults.standard.object(forKey: limitKey) as? Int else {
                return defaultLimitMB
            }
            return stored
        }
        set { UserDefaults.standard.set(newValue, forKey: limitKey) }
    }
    static var limitBytes: Int64 { Int64(limitMB) * 1024 * 1024 }
}

/// Watches the pasteboard and hangs whatever was copied.
///
/// Tendedero only took images, and only when the user turned it on. For
/// Clothespeg this is the main way anything reaches the line, so it is on
/// from the first launch and the menu item is there to pause it.
///
/// The pasteboard has no change notification, so its change count is checked
/// twice a second.
@MainActor
final class ClipboardWatcher {
    private let onItem: (Payload, Origin, RichText?) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// Which app was in front when the pasteboard last changed. The
    /// pasteboard will not say whose copy it was, and this is the app the
    /// user was copying from.
    private var lastOwner: String?
    private var appObserver: NSObjectProtocol?

    private static let enabledKey = "clipboardEnabled"

    /// On unless the user has paused it. `bool(forKey:)` cannot tell "off"
    /// from "never written", so the key is written at launch instead.
    static var isEnabled: Bool {
        get {
            guard UserDefaults.standard.object(forKey: enabledKey) != nil else { return true }
            return UserDefaults.standard.bool(forKey: enabledKey)
        }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Types that mean the copy is nothing to show. Password managers mark
    /// their copies private or temporary, following nspasteboard.org, and
    /// those must never hang. Checked before anything else is read.
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// A picture copied off the line comes back as its own file, which would
    /// otherwise hang a second card of something already on the line. A file
    /// copied anywhere else is a reference to somewhere, and hanging it is
    /// the point: it drags out as the file itself, and it is the file
    /// itself rather than a copy that has to be kept and cleaned up.

    private static let maxBytes = 16 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000
    /// A card shows a few lines. Far past this it is a paste, not a snippet,
    /// and hanging it would help nobody.
    nonisolated private static let maxTextCharacters = 20_000

    init(onItem: @escaping (Payload, Origin, RichText?) -> Void) {
        self.onItem = onItem
        watchFrontmostApp()
    }

    /// Clothingpeg is a status-bar app: it never becomes frontmost on its own,
    /// but it can when the user clicks a card. Watching the change keeps
    /// `lastOwner` pointing at the app the user is really in, and covers the
    /// case where a copy arrives without the frontmost app having changed.
    private func watchFrontmostApp() {
        appObserver = NotificationCenter.default.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) {
            [weak self] note in
            MainActor.assumeIsolated {
                // The notification carries the app that came to the front, so
                // there is no need to ask the workspace again.
                guard let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
                else { return }
                self?.noteFrontmost(app)
            }
        }
        noteFrontmost(NSWorkspace.shared.frontmostApplication)
    }

    /// The app in front is where a copy comes from. Clothespeg's own name is
    /// never the answer: taking something back off a card is taking from
    /// Clothespeg, not bringing something new to it.
    ///
    /// Reaching Clothespeg leaves the last real app remembered rather than
    /// erasing it. The user did not go anywhere — clicking a card makes this
    /// app key without the user having switched — and a copy made a moment
    /// later still came from the app they were working in.
    private func noteFrontmost(_ app: NSRunningApplication?) {
        guard let name = app?.localizedName, !Self.selfNames.contains(name) else { return }
        lastOwner = name
    }

    /// The app a copy came from, read at the moment the copy is noticed.
    ///
    /// The pasteboard will not say whose copy it was and there is no public
    /// API that does, so this is the app that was in front. It is read here
    /// rather than remembered from a notification, because the user may have
    /// switched away in the time since, and the last app they were in is the
    /// one that had the copy.
    private func noteSourceApp() {
        noteFrontmost(NSWorkspace.shared.frontmostApplication)
    }

    private static let selfNames: Set<String> = ["Clothespeg", "Tendedero"]

    func start() {
        guard timer == nil else { return }
        // Whatever is on the pasteboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        // A third of a second, not half. The pasteboard has no change
        // notification, so the interval is also how stale the source app can
        // be: copy, switch window, and the name on the card is the one you
        // just left. The cost is a third as many change-count reads, which
        // is a very cheap question to ask.
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Set when this app wrote the pasteboard itself, so the copy it just
    /// made is not read back as a copy the user made.
    ///
    /// A card clicked to be copied writes here, the pasteboard changes, and
    /// the watcher sees a change it did not expect — which it then hangs as a
    /// new card of something already on the line, and clicking that one does
    /// it again. The count check alone cannot catch that: the count really
    /// did move. What tells them apart is who asked: a copy this app made is
    /// not news, and the marker is cleared as soon as it has been seen.
    static let ourWrite = NSPasteboard.PasteboardType("app.clothespeg.ownWrite")

    /// Where this app keeps the screenshots it has taken, which is not a place
    /// the user copied from and so is never what a file card refers to.
    static let ownFolder: String = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("Clothespeg/Pictures").path + "/"
    }()

    /// Whether the pasteboard's current contents are one of ours, marked by
    /// the writer rather than guessed from a name in the source app: a copy
    /// made while Clothespeg happened to be frontmost would be misread
    /// otherwise, since the user did not go anywhere.
    func isOurWrite(_ pb: NSPasteboard) -> Bool {
        pb.types?.contains(Self.ourWrite) ?? false
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        // Ours: the user did not copy anything, this app did. Remembering the
        // count keeps the check from tripping again on the next poll.
        guard !isOurWrite(pb) else { return }
        // Said rather than silent: a change that hangs nothing is exactly
        // the question a bug report has to answer, and the types are the
        // answer. Skipped-private is logged too, because a screenshot tool
        // that marks its capture transient looks identical to a hang that
        // never happened.
        guard let items = pb.pasteboardItems, !items.isEmpty else {
            diagLog("Pasteboard changed with no items, types: \((pb.types ?? []).map(\.rawValue).joined(separator: ", "))")
            return
        }
        let types = Set(items.flatMap(\.types))
        guard Self.privateTypes.isDisjoint(with: types),
              pb.changeCount == count else {
            diagLog("Pasteboard change skipped, private types: \(types.intersection(Self.privateTypes).map(\.rawValue).joined(separator: ", "))")
            return
        }

        // Read the app in front now rather than at hang time: a large picture
        // takes a moment to decode, and the user may have moved on by then.
        noteSourceApp()
        // A picture copied out of this app's own picture folder is a card's
        // own file coming back, which would hang a second card of something
        // already hanging. Said rather than silent, because from the outside
        // a silent skip is exactly what a watcher that died looks like.
        if isOwnPictureCopy(pb) {
            diagLog("Picture copy skipped: it is a card's own file coming back")
            return
        }
        // A file first, and the order matters. The Finder offers a copied
        // file three ways — as a URL, as a picture of its icon, and as its
        // name as text — so whichever of those is asked for first is the one
        // that gets hung. A file asked for last never hangs at all, because
        // the name is always there to answer the text question. A picture is
        // a file too, and is asked for after this one, which is why a copied
        // image shows itself rather than a Finder icon.
        if let payload = filePayload(from: pb) {
            hang(payload)
        } else if let payload = imagePayload(from: pb, count: count) {
            hang(payload)
        } else if let (text, rich) = textPayload(from: pb) {
            hang(text, rich: rich)
        } else {
            let described = items.flatMap(\.types).map { type -> String in
                let size = pb.data(forType: type).map { " \($0.count)B" } ?? ""
                return type.rawValue + size
            }
            diagLog("Pasteboard changed but nothing hung: \(described.joined(separator: ", "))")
        }
    }

    /// A picture, if this copy is one. PNG is taken as it is; TIFF becomes
    /// PNG. The result has to decode and be a sane size.
    /// A file, if this copy is one — read from the URL the pasteboard
    /// carries rather than from any file, so nothing is opened or read to
    /// find out what was copied.
    ///
    /// An image is a file too, and the Finder offers both for one. The
    /// picture path wins for those, because a screenshot hung as a picture
    /// shows itself, while a screenshot hung as a file would show a Finder
    /// icon and a name. So this only takes what the picture path did not.
    /// Files, if this copy is any — read from the URLs the pasteboard
    /// carries rather than from any file, so nothing is opened to find out
    /// what was copied.
    ///
    /// The file type is a newline-separated list, so a selection of twenty is
    /// twenty lines in one string and asking for it as a single path gets a
    /// path that does not exist. That is why copying several files hung
    /// nothing at all rather than hanging the first one.
    ///
    /// An image is a file too, and the Finder offers both for one. The
    /// picture path wins for those, because a screenshot hung as a picture
    /// shows itself while a screenshot hung as a file would show a Finder
    /// icon and a name. So this only takes what the picture path did not,
    /// which is why it is asked for first and the picture path second.
    private func filePayload(from pb: NSPasteboard) -> Payload? {
        // Two ways in, because the Finder uses two. `public.file-url` is one
        // string, newline-separated, which is what a single file looks like
        // and what several look like if the source bothers to join them. But
        // the Finder also writes `NSFilenamesPboardType`, a property list of
        // paths, and a selection copied there is only visible through that.
        // Reading one and not the other is how copying three files hung
        // nothing: the list was there the whole time, under the other name.
        let candidates = pasteboardFileCandidates(pb)

        // Folders are files as far as a pasteboard is concerned, and a folder
        // copied in the Finder is a thing you put files into — worth a card,
        // which shows its icon and its name and drags out as itself.
        //
        // What is dropped is anything under this app's own picture folder: a
        // screenshot copied off the line comes back with its own URL, and it
        // is what made a dragged card turn into a .png on the desktop — the
        // file went out that was asked for, and what was asked for was the
        // capture rather than the selection.
        let ours = Self.ownFolder
        let urls = candidates.filter { url in
            guard !url.path.hasPrefix(ours) else { return false }
            var isDirectory: ObjCBool = false
            return FileManager.default.fileExists(atPath: url.path, isDirectory: &isDirectory)
        }
        // The two sources overlap — the Finder writes both for one selection —
        // so the same path twice is one file copied once.
        var seen = Set<String>()
        let unique = urls.filter { seen.insert($0.path).inserted }
        guard !unique.isEmpty else { return nil }
        // One picture file, within the limit, hangs as the picture it is: the
        // card keeps its own copy in the app's folder, so it outlives the
        // original. The switch off, the oversize, and every selection of more
        // than one stay references, exactly as any other file hangs.
        if ImageFileHanging.isEnabled, unique.count == 1, let only = unique.first,
           only.isImageFile, only.diskBytes > 0, only.diskBytes <= ImageFileHanging.limitBytes,
           let payload = ownCopy(of: only) {
            return payload
        }
        return .file(unique)
    }

    /// Writes the app's own copy of a picture file and hangs it as a picture.
    ///
    /// The copy carries the original's name, because the name is half of what
    /// a file is — dragged out again, it arrives as the file it was. A name
    /// already taken in the folder is joined by the copy's own stamp, the way
    /// the clipboard's pictures name themselves. A copy that cannot be written
    /// leaves the file hanging as a reference instead, which is the card the
    /// file would have worn anyway.
    private func ownCopy(of url: URL) -> Payload? {
        Inbox.prepare()
        var target = Inbox.folder.appendingPathComponent(url.lastPathComponent)
        if FileManager.default.fileExists(atPath: target.path) {
            let base = url.deletingPathExtension().lastPathComponent
            let ext = url.pathExtension
            let stamped = ext.isEmpty ? "\(base) \(Self.stamp())" : "\(base) \(Self.stamp()).\(ext)"
            target = Inbox.folder.appendingPathComponent(stamped)
        }
        do {
            try FileManager.default.copyItem(at: url, to: target)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: target.path)
            return .image(target)
        } catch {
            log.error("Could not keep a copy of a picture file: \(error.localizedDescription, privacy: .public)")
            return nil
        }
    }

    /// Every file reference the pasteboard carries, by either of the two
    /// names the Finder writes them under.
    private func pasteboardFileCandidates(_ pb: NSPasteboard) -> [URL] {
        var candidates: [URL] = []
        if let raw = pb.string(forType: .fileURL) {
            candidates += raw.split(separator: "\n", omittingEmptySubsequences: true)
                .compactMap { Self.fileURL(from: $0) }
        }
        if let data = pb.data(forType: NSPasteboard.PasteboardType("NSFilenamesPboardType")),
           let paths = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [String] {
            candidates += paths.compactMap { Self.fileURL(from: $0) }
        }
        return candidates
    }

    /// Whether this copy is one of this app's own card pictures coming home:
    /// a picture file copied out of the app's own picture folder offers a
    /// file URL that points there. Hanging it would be a second card of
    /// something already hanging. Judged from where the file lives rather
    /// than from what hung last, because a judgement from history swallows
    /// every new screenshot that follows a screenshot.
    private func isOwnPictureCopy(_ pb: NSPasteboard) -> Bool {
        let existing = pasteboardFileCandidates(pb).filter {
            FileManager.default.fileExists(atPath: $0.path)
        }
        guard !existing.isEmpty else { return false }
        return existing.allSatisfy { $0.path.hasPrefix(Self.ownFolder) }
    }

    /// One line of a pasteboard's file list: either a URL or a bare path,
    /// depending on who wrote it.
    private static func fileURL(from line: some StringProtocol) -> URL? {
        let text = line.trimmingCharacters(in: .whitespaces)
        guard !text.isEmpty else { return nil }
        let path = text.hasPrefix("file:")
            ? (URL(string: String(text))?.path ?? String(text))
            : String(text)
        let url = URL(fileURLWithPath: (path as NSString).expandingTildeInPath)
        return url.isFileURL ? url : nil
    }

    private func imagePayload(from pb: NSPasteboard, count: Int) -> Payload? {
        // Three types, because screenshot tools do not agree on one. And the
        // size cap is judged on the PNG that comes out, not on the data that
        // goes in: the raw side of a full-screen capture is an uncompressed
        // TIFF, tens of megabytes before a pixel of it is decoded, and the
        // old cap on it turned every full-screen screenshot away at the door
        // while other clipboard managers took the same frame fine. Decoding
        // costs a moment; missing every capture cost more.
        guard let type = pb.availableType(from: [.png, .tiff, .init("public.jpeg")]),
              let data = pb.data(forType: type),
              pb.changeCount == count,
              let png = Self.png(from: data, type: type) else { return nil }
        guard png.count <= Self.maxBytes else {
            diagLog("Picture skipped: \(png.count) bytes is over the \(Self.maxBytes) cap")
            return nil
        }
        // An image card is a file, so the picture is written into the app's
        // own folder with permissions only its owner can read.
        return save(image: png)
    }

    /// A string, if this copy is one. Text is tried first: a copy from a rich
    /// document can offer both a string and a picture of itself, and the
    /// words are what the user copied.
    ///
    /// Whatever rich dressing rides beside the words is read too, and kept
    /// whether the copy-with-formatting switch is on or not: the choice is
    /// read when a card goes out, so a card hung plain can still be copied
    /// rich later. Reading it is two questions the pasteboard has already
    /// answered; skipping them would save nothing.
    private func textPayload(from pb: NSPasteboard) -> (Payload, RichText?)? {
        guard let string = pb.string(forType: .string) else { return nil }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.count <= Self.maxTextCharacters else { return nil }
        return (.text(trimmed, isCode: Self.looksLikeCode(trimmed)),
                RichText.from(pasteboard: pb))
    }

    /// A guess at whether this text wants a monospaced face: it runs over
    /// several lines, or carries a mark that prose rarely has. Only the font
    /// changes, so a wrong guess costs nothing.
    nonisolated private static func looksLikeCode(_ s: String) -> Bool {
        if s.contains("\n") { return true }
        return ["{", "}", "();", "=>", "::", "</"].contains { s.contains($0) }
    }

    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    private func save(image png: Data) -> Payload {
        // No look at what hung before: the copy just made is this copy's own
        // card, whatever the last one was. The old look — "the last card was
        // a picture, so reuse it" — swallowed every screenshot that followed
        // a screenshot: the capture decoded, the hang went out, and what hung
        // was the old picture wearing the new time, which reads on the line
        // as the screenshot never having arrived.
        let fm = FileManager()
        let url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()).png")
        do {
            Inbox.prepare()
            try png.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return .image(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a copied picture: \(error.localizedDescription, privacy: .public)")
            // A file that cannot be written still leaves the card on the line:
            // the payload it reports keeps the user from waiting for nothing.
            return .image(url)
        }
    }

    /// Hangs what was read off the pasteboard.
    ///
    /// No guard on what it is. Copying the same snippet twice is two things
    /// that happened at two different minutes, and the pasteboard knows they
    /// were two copies because its change count moved — so the change count
    /// is the identity, not the content. Comparing content here meant that
    /// copying the same colour twice hung one card, which is the app
    /// deciding on the user's behalf that they had not meant to do it twice.
    private func hang(_ payload: Payload, rich: RichText? = nil) {
        onItem(payload, Origin(app: lastOwner), rich)
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}